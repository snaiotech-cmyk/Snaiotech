-- ── Row Level Security ───────────────────────────────────────
alter table public.page_settings enable row level security;
alter table public.site_settings enable row level security;
alter table public.submissions enable row level security;

-- Page settings policies
do $$
begin
  if not exists (select 1 from pg_policies where tablename = 'page_settings' and policyname = 'Public can read page settings') then
    create policy "Public can read page settings" on public.page_settings for select using (true);
  end if;
  if not exists (select 1 from pg_policies where tablename = 'page_settings' and policyname = 'Admins manage page settings') then
    create policy "Admins manage page settings" on public.page_settings for all to authenticated
      using (exists (select 1 from public.admin_users where user_id = auth.uid()))
      with check (exists (select 1 from public.admin_users where user_id = auth.uid()));
  end if;
end $$;

