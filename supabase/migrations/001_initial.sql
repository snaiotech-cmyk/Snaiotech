-- ── Tables ──────────────────────────────────────────────────

create table if not exists public.page_settings (
  id          bigint generated by default as identity primary key,
  page        text not null unique,
  title       text not null default '',
  slug        text not null unique,
  description text not null default '',
  keywords    text not null default '',
  indexable   boolean not null default true,
  updated_at  timestamptz not null default now()
);

create table if not exists public.site_settings (
  id                  boolean primary key default true,
  site_name           text not null default 'Snaiotech',
  logo_url            text not null default '',
  favicon_url         text not null default '',
  canonical_url       text not null default 'https://snaiotech.com',
  default_description text not null default '',
  og_image_url        text not null default '',
  instagram           text not null default 'https://www.instagram.com/snaiotech/',
  facebook            text not null default 'https://www.facebook.com/snaiotech',
  linkedin            text not null default 'https://www.linkedin.com/in/snaiotech/',
  email               text not null default 'Info@snaiotech.com',
  robots              text not null default 'index, follow',
  schema_type         text not null default 'ProfessionalService',
  ga_id               text not null default '',
  gsc_verification    text not null default '',
  geo_region          text not null default 'IN-TN',
  geo_placename       text not null default 'Chennai, Tamil Nadu, India',
  geo_position        text not null default '13.0827;80.2707',
  updated_at          timestamptz not null default now()
);

create table if not exists public.submissions (
  id         uuid primary key default gen_random_uuid(),
  name       text not null,
  email      text not null,
  company    text not null default '',
  service    text not null default '',
  message    text not null,
  status     text not null default 'new' check (status in ('new', 'contacted', 'archived')),
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);

-- ── Add new columns to existing tables (idempotent) ─────────
do $$
begin
