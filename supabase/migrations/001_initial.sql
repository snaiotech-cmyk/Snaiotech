-- Submissions policies
do $$
begin
  if not exists (select 1 from pg_policies where tablename = 'submissions' and policyname = 'Anyone can submit contact form') then
    create policy "Anyone can submit contact form" on public.submissions for insert with check (true);
  end if;
  if not exists (select 1 from pg_policies where tablename = 'submissions' and policyname = 'Admins read submissions') then
    create policy "Admins read submissions" on public.submissions for select to authenticated
      using (exists (select 1 from public.admin_users where user_id = auth.uid()));
  end if;
  if not exists (select 1 from pg_policies where tablename = 'submissions' and policyname = 'Admins update submissions') then
    create policy "Admins update submissions" on public.submissions for update to authenticated
      using (exists (select 1 from public.admin_users where user_id = auth.uid()))
      with check (exists (select 1 from public.admin_users where user_id = auth.uid()));
  end if;
end $$;

